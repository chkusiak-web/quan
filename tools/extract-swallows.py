"""Lift the two swallows painted in the original reference (before they were
erased from the map) and write them as sprites: src/pixmap/swallows.js.

Each swallow gets two frames: the painted glide pose, and a flap with the
raised wing folded halfway down toward the body.

Usage: python3 tools/extract-swallows.py original-512x320.png
"""
import colorsys
import json
import sys
from PIL import Image

im = Image.open(sys.argv[1]).convert('RGB')

# (box in the original, first row of the body: rows above it are the wing)
BIRDS = {'near': ((219, 45, 238, 63), 10), 'far': ((269, 79, 283, 90), 5)}


def is_bird(c):
    h, s, v = colorsys.rgb_to_hsv(*(k / 255 for k in c))
    return not (0.53 < h < 0.62 and s > 0.25 and v > 0.85)   # anything but sky blue


out = {}
for name, ((x0, y0, x1, y1), body) in BIRDS.items():
    glide = []
    for y in range(y0, y1):
        for x in range(x0, x1):
            c = im.getpixel((x, y))
            if is_bird(c):
                glide.append([x - x0, y - y0, '#%02x%02x%02x' % c])
    # Flap: the wing above the body folds halfway down.
    flap = {}
    for dx, dy, c in glide:
        if dy < body:
            dy = body - (body - dy) // 2
        flap.setdefault((dx, dy), c)
    out[name] = {'w': x1 - x0, 'frames': [glide, [[x, y, c] for (x, y), c in flap.items()]]}

with open('src/pixmap/swallows.js', 'w') as f:
    f.write('// Generated by tools/extract-swallows.py from the original reference.\n')
    f.write('// Two swallows, facing right; frames are [dx, dy, colour] pixels.\n\n')
    f.write('export const SWALLOWS = ' + json.dumps(out) + ';\n')
print({k: [len(fr) for fr in v['frames']] for k, v in out.items()})
