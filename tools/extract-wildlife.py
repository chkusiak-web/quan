"""Lift the ducks and the egret painted in the original reference, with their
reflections, and write them as sprites: src/pixmap/wildlife.js.

A sprite pixel is any pixel in the bird's box that differs between the
original map and the cleaned map (where the birds were painted out).

Usage: python3 tools/extract-wildlife.py original.png cleaned.png
"""
import json
import sys
from PIL import Image

orig = Image.open(sys.argv[1]).convert('RGB')
clean = Image.open(sys.argv[2]).convert('RGB')

BOXES = {
    'duck': (421, 197, 433, 210),    # the darker drake, with its reflection
    'hen': (433, 197, 449, 210),     # the browner hen
    'egret': (458, 189, 482, 223),   # standing, with its long reflection
}


def lift(x0, y0, x1, y1):
    px = []
    for y in range(y0, y1):
        for x in range(x0, x1):
            a, b = orig.getpixel((x, y)), clean.getpixel((x, y))
            if sum(abs(p - q) for p, q in zip(a, b)) > 30:
                px.append([x - x0, y - y0, '#%02x%02x%02x' % a])
    return px


def keep_shapes(px, min_size):
    """Drop specks: keep only connected groups of at least min_size pixels."""
    left = {(x, y): c for x, y, c in px}
    kept = []
    while left:
        start = next(iter(left))
        group, todo = [], [start]
        while todo:
            p = todo.pop()
            if p not in left:
                continue
            group.append((p, left.pop(p)))
            x, y = p
            todo += [(x + dx, y + dy) for dx in (-1, 0, 1) for dy in (-1, 0, 1)]
        if len(group) >= min_size:
            kept += [[x, y, c] for (x, y), c in group]
    return kept


MIN_SIZE = {'duck': 4, 'hen': 4, 'egret': 8}
LILY = (476, 189, 482, 199)   # a lily pad inside the egret's box

out = {}
for name, box in BOXES.items():
    px = lift(*box)
    if name == 'egret':
        px = [p for p in px if not (LILY[0] <= p[0] + box[0] < LILY[2] and LILY[1] <= p[1] + box[1] < LILY[3])]
    px = keep_shapes(px, MIN_SIZE[name])
    out[name] = {'x': box[0], 'y': box[1], 'w': box[2] - box[0], 'pixels': px}

# The egret's head-down frame: the head and upper neck dip forward and
# down, as when it peers into the water.
eg = out['egret']['pixels']
dip = {}
head = min(y for _, y, _ in eg)
for x, y, c in eg:
    if y < head + 5:                  # head and upper neck
        x, y = x - 1, y + 4          # it faces left
    elif y < head + 7:                # the neck bends
        x = x + 1
    dip.setdefault((x, y), c)
out['egret']['dip'] = [[x, y, c] for (x, y), c in dip.items()]

with open('src/pixmap/wildlife.js', 'w') as f:
    f.write('// Generated by tools/extract-wildlife.py from the original reference.\n')
    f.write('// Ducks and the egret with their reflections; pixels are [dx, dy, colour]\n')
    f.write('// from the top-left of where each was painted (x, y).\n\n')
    f.write('export const WILDLIFE = ' + json.dumps(out) + ';\n')
print({k: len(v['pixels']) for k, v in out.items()})
