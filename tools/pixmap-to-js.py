"""Write a palette-indexed PNG from pixelate.py as a JS module.

Usage: python3 tools/pixmap-to-js.py public/reference/baotu-512x320.png src/pixmap/baotu.js
"""
import base64
import sys
from PIL import Image

src, dst = sys.argv[1], sys.argv[2]
im = Image.open(src)
assert im.mode == "P", "expected a palette PNG from pixelate.py"
w, h = im.size
used = sorted({i for _, i in im.getcolors()})
remap = {old: new for new, old in enumerate(used)}
pal = im.getpalette()
colors = ["#%02x%02x%02x" % tuple(pal[i * 3:i * 3 + 3]) for i in used]
table = bytes(remap.get(i, 0) for i in range(256))
data = im.tobytes().translate(table)

hexes = ",\n".join("  " + ", ".join(f"'{c}'" for c in colors[i:i + 8]) for i in range(0, len(colors), 8))
b64 = base64.b64encode(data).decode()
lines = "\n".join(f"  '{b64[i:i + 120]}' +" for i in range(0, len(b64), 120)).rstrip(" +")

with open(dst, "w") as f:
    f.write(f"""// Generated by tools/pixmap-to-js.py from {src}. Do not edit by hand.
// {w} x {h} pixels, {len(colors)} colours. Each pixel is one byte: an index into PALETTE.

export const W = {w};
export const H = {h};

export const PALETTE = [
{hexes},
];

export const PIXELS = Uint8Array.from(atob(
{lines}
), (c) => c.charCodeAt(0));
""")
print(dst, w, h, len(colors), "colours")
